// Migration helper: retain the light design, expose legacy literals through semantic tokens.
// This is a build-time source migration, never executed by a browser or imported config.
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";
const cssFiles = [];
function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p);
    else if (
      p.endsWith(".css") &&
      !/themes\.css|palette\.css|control-center\.css/.test(p)
    )
      cssFiles.push(p);
  }
}
walk("src");
const colors = new Map();
for (const file of cssFiles) {
  const root = postcss.parse(fs.readFileSync(file, "utf8"));
  root.walkDecls((d) => {
    if (d.prop.startsWith("--")) return;
    if (d.value.includes("--pl-")) {
      for (const m of d.value.matchAll(
        /(--pl-(text|bg|line)-([a-f0-9]{6,8}))/g,
      ))
        colors.set(m[1], { hex: "#" + m[3], role: m[2] });
      return;
    }
    const role =
      d.prop === "color"
        ? "text"
        : /background/.test(d.prop)
          ? "bg"
          : /border|outline|shadow|decoration/.test(d.prop)
            ? "line"
            : "text";
    d.value = d.value.replace(/#[a-f\d]{3,8}\b/gi, (hex) => {
      let raw = hex.slice(1).toLowerCase();
      if (raw.length === 3 || raw.length === 4)
        raw = [...raw].map((x) => x + x).join("");
      const key = `--pl-${role}-${raw}`;
      colors.set(key, { hex: "#" + raw, role });
      return `var(${key}, ${hex})`;
    });
  });
  fs.writeFileSync(file, root.toString());
}
function channels(hex) {
  const rgb = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(...rgb),
    min = Math.min(...rgb),
    delta = max - min;
  let hue = 0;
  if (delta)
    hue =
      max === rgb[0]
        ? ((rgb[1] - rgb[2]) / delta) % 6
        : max === rgb[1]
          ? (rgb[2] - rgb[0]) / delta + 2
          : (rgb[0] - rgb[1]) / delta + 4;
  return {
    l: rgb.reduce((s, x, i) => s + x * [0.2126, 0.7152, 0.0722][i], 0),
    sat: delta,
    h: (((hue * 60) % 360) + 360) % 360,
    alpha: hex.length === 9 ? hex.slice(7) : "",
  };
}
const palettes = {
  dark: {
    paper: "#192235",
    tint: "#242e45",
    green: "#1c352f",
    warm: "#3a2d35",
    text: "#edf2fc",
    muted: "#b2c1d8",
    line: "#3b4b65",
    primary: "var(--primary)",
    button: "var(--button-bg)",
    good: "#84dfaa",
    bad: "#ffad9f",
    gold: "#f2d28a",
  },
  finance: {
    paper: "#10212c",
    tint: "#192f3f",
    green: "#153b32",
    warm: "#3c2c2e",
    text: "#e6f3f6",
    muted: "#aec6d0",
    line: "#355363",
    primary: "var(--primary)",
    button: "var(--button-bg)",
    good: "#83e6a6",
    bad: "#ffb4a9",
    gold: "#e7cf96",
  },
  christmas: {
    paper: "#ffffff",
    tint: "#eef5f0",
    green: "#e6f1e6",
    warm: "#fff0ed",
    text: "#243e33",
    muted: "#536b5e",
    line: "#c4d9cc",
    primary: "var(--primary)",
    button: "var(--button-bg)",
    good: "#176c44",
    bad: "#ac3540",
    gold: "#8a6018",
  },
};
let output =
  "/* Curated semantic replacements for legacy light palette literals. Generated by tokenize-themes.mjs. */\n";
for (const [theme, p] of Object.entries(palettes)) {
  output += `html[data-theme="${theme}"] {\n`;
  for (const [key, { hex, role }] of colors) {
    const { l, sat, h, alpha } = channels(hex);
    const blue = h >= 180 && h <= 300 && sat > 0.15;
    const green = h >= 65 && h < 180 && sat > 0.15;
    const warm = (h < 65 || h > 300) && sat > 0.15;
    let value;
    if (role === "line") value = p.line;
    else if (role === "text") {
      value = blue
        ? p.primary
        : green
          ? p.good
          : warm
            ? h < 45
              ? p.bad
              : p.gold
            : l < 0.16 || (theme !== "christmas" && l > 0.9)
              ? p.text
              : p.muted;
    } else {
      value =
        l > 0.72
          ? green
            ? p.green
            : warm
              ? p.warm
              : l > 0.96
                ? p.paper
                : p.tint
          : blue
            ? p.button
            : green
              ? theme === "christmas"
                ? "#1c714d"
                : "#235c4c"
              : warm
                ? theme === "christmas"
                  ? "#a52f3c"
                  : "#7e4550"
                : l < 0.2
                  ? theme === "christmas"
                    ? "#163d30"
                    : p.paper
                  : p.tint;
    }
    if (alpha && /^#[a-f\d]{6}$/i.test(value)) value += alpha;
    output += `  ${key}: ${value};\n`;
  }
  output += "}\n";
}
fs.writeFileSync("src/palette.css", output);
console.log(
  `Tokenized ${colors.size} semantic colors in ${cssFiles.length} stylesheets.`,
);
