export default function ConceptComparison({ scene }: { scene: Scene }) {
  const [active, setActive] = useState<number | null>(null);
  return (
    <>
      <div className="concept-situation">
        <Lightbulb size={17} />
        {scene.situation}
      </div>
      <h3>{scene.prompt}</h3>
      <div className="visual-compare">
        {scene.options.map((o, i) => (
          <button
            key={o.label}
            className={active === i ? "selected" : ""}
            aria-pressed={active === i}
            onClick={() => setActive(i)}
          >
            <span>{o.label}</span>
            <strong>{o.value}</strong>
            <ArrowRight size={17} />
          </button>
        ))}
      </div>
      {active === null ? (
        <p className="concept-prompt">
          Нажми на карточку, чтобы разобрать смысл показателя или решения.
        </p>
      ) : (
        <p className="visual-explanation" role="status">
          {scene.options[active].why}
        </p>
      )}
    </>
  );
}
